import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
process.env.SQL_DRIVER='pglite';process.env.LOCAL_TRIAL='true';
process.env.PGLITE_DATA_DIR=mkdtempSync(resolve('../qa-backend-'));
const {localDatabase}=await import('../src/db/index.ts');
const db=await import('../src/db/warehouseDb.ts');
const row={Order_ID:'QA-ATOMIC',SKU_ID:'QA-SKU',Nama_Barang:'Uji transaksi',Operator_ID:'QA',Waktu_Proses:'2026-10-30',Kondisi:'Good'};
await Promise.all([db.ensureDatabaseSeeded(),db.ensureDatabaseSeeded(),db.ensureDatabaseSeeded()]);
await db.dbSetAllReturns([row]);
await assert.rejects(db.dbSaveReturns([{...row,SKU_ID:'SHOULD-ROLL-BACK'},null],row.Order_ID));
assert.deepEqual((await db.getWarehouseData()).returns.map(r=>r.SKU_ID),['QA-SKU']);
await assert.rejects(db.dbSetAllReturns([{...row,SKU_ID:'PARTIAL'},null]));
assert.deepEqual((await db.getWarehouseData()).returns.map(r=>r.SKU_ID),['QA-SKU']);
await assert.rejects(db.dbSaveDisputes({'QA-ATOMIC':{note:'must roll back'},'QA-BAD':{value:1n}}));
assert.equal((await db.getWarehouseData()).disputes['QA-ATOMIC'],undefined);
await db.dbSetAllReturns([]);
await localDatabase.close();
const restarted=spawnSync(process.execPath,['--import','tsx','tests/backend-reopen.mjs'],{cwd:process.cwd(),env:process.env,encoding:'utf8'});
assert.equal(restarted.status,0,restarted.stdout+'\n'+restarted.stderr);
console.log('PASS: rollback for return replacement and multi-record claims; empty returns survive restart; seed initialization is shared. Isolated test database only.');
